import { useEditor } from '../store';
import type { AudioItem } from '../types';
import { uid } from '../lib/defaults';
import { layoutClips, totalDuration } from '../lib/timeline';
import { player, usePlayer } from '../lib/player';
import { addMediaFile } from '../lib/projectIO';
import { SOUNDS, getSoundAsset, previewSound, type SoundDef } from '../lib/soundLibrary';
import { pickFiles } from './ClipStrip';
import { Section, Slider, Toggle, secs } from './ui';
import { toast } from './Toast';
import { IconTrash } from './Icons';

function newItem(assetId: string, kind: 'music' | 'sfx', start: number, length: number, loop: boolean): AudioItem {
  return {
    id: uid(), assetId, kind, start, in: 0, length, loop, volume: kind === 'music' ? 0.6 : 0.9,
    fadeIn: kind === 'music' ? 1 : 0, fadeOut: kind === 'music' ? 1.5 : 0, duck: kind === 'music',
  };
}

export function AudioPanel() {
  const selection = useEditor((s) => s.selection);
  const items = useEditor((s) => s.project.audio.items);
  const item = selection?.type === 'audio' ? items.find((i) => i.id === selection.id) : undefined;
  return item ? <ItemInspector it={item} /> : <AudioLibrary />;
}

function AudioLibrary() {
  const project = useEditor((s) => s.project);
  const { addAudioItem, update } = useEditor.getState();
  const total = totalDuration(project.clips);

  const addSound = async (def: SoundDef) => {
    try {
      const a = await getSoundAsset(def);
      const start = def.kind === 'music' ? 0 : Math.min(player.getTime(), Math.max(0, total - 0.1));
      const length = def.kind === 'music' ? Math.max(1, total) : a.duration;
      addAudioItem(newItem(a.id, def.kind, start, length, def.kind === 'music'));
      toast(`${def.name} added`, 'success', 1500);
    } catch (err) {
      toast(`Could not create sound: ${(err as Error).message}`, 'error');
    }
  };

  const importAudio = async (kind: 'music' | 'sfx') => {
    const files = await pickFiles('audio/*,.mp3,.m4a,.wav,.aac', kind === 'sfx');
    for (const f of files) {
      try {
        const a = await addMediaFile(f, f.name);
        if (a.kind !== 'audio') throw new Error('Please choose an audio file (MP3, M4A, WAV).');
        const start = kind === 'music' ? 0 : player.getTime();
        addAudioItem(newItem(a.id, kind, start, kind === 'music' ? Math.min(Math.max(1, total), a.duration) : a.duration, false));
      } catch (err) {
        toast(`Could not import "${f.name}": ${(err as Error).message}`, 'error');
      }
    }
  };

  /** Put one sound on every cut that has a transition (or every cut), timed to the visual event. */
  const matchToCuts = async (def: SoundDef) => {
    const placed = layoutClips(project.clips);
    const cuts = placed.slice(1).filter((p) => p.clip.transition.type !== 'none');
    const points = (cuts.length ? cuts : placed.slice(1)).map((p) => p.start);
    if (!points.length) { toast('Add at least two clips first.', 'warn'); return; }
    const a = await getSoundAsset(def);
    // Whooshes peak mid-sound, so start them a little before the cut.
    const lead = def.id === 'whoosh' ? 0.32 : def.id === 'swipe' ? 0.08 : 0;
    const newItems = points.map((t) => newItem(a.id, 'sfx', Math.max(0, t - lead), a.duration, false));
    update((p) => ({ ...p, audio: { ...p.audio, items: [...p.audio.items, ...newItems] } }));
    toast(`${def.name} placed on ${newItems.length} ${cuts.length ? 'transition' : 'cut'}${newItems.length > 1 ? 's' : ''}`, 'success', 2500);
  };

  const matchToGraphics = async (def: SoundDef) => {
    const starts = [...new Set(project.overlays.filter((o) => o.kind !== 'image').map((o) => Math.round(o.start * 100) / 100))];
    if (!starts.length) { toast('Add a text or graphic first.', 'warn'); return; }
    const a = await getSoundAsset(def);
    const newItems = starts.map((t) => newItem(a.id, 'sfx', t, a.duration, false));
    update((p) => ({ ...p, audio: { ...p.audio, items: [...p.audio.items, ...newItems] } }));
    toast(`${def.name} placed on ${newItems.length} graphic${newItems.length > 1 ? 's' : ''}`, 'success', 2500);
  };

  const music = SOUNDS.filter((s) => s.kind === 'music');
  const sfx = SOUNDS.filter((s) => s.kind === 'sfx');
  const byId = (id: string) => SOUNDS.find((s) => s.id === id)!;

  return (
    <div className="panel-stack" data-testid="audio-library">
      <Section title="Background music">
        {music.map((s) => <SoundRow key={s.id} def={s} onAdd={() => void addSound(s)} />)}
        <button className="secondary-btn sm" onClick={() => void importAudio('music')} data-testid="import-music">Import your music…</button>
        <p className="muted small">Built-in beds are generated by the app (royalty-free). Only import music you own or have a licence for.</p>
      </Section>
      <Section title="Sound effects">
        {sfx.map((s) => <SoundRow key={s.id} def={s} onAdd={() => void addSound(s)} />)}
        <button className="secondary-btn sm" onClick={() => void importAudio('sfx')}>Import sound effects…</button>
      </Section>
      <Section title="Match sounds to the edit">
        <p className="muted small">Places effects exactly on visual events instead of at random.</p>
        <div className="btn-row two">
          <button className="secondary-btn sm" onClick={() => void matchToCuts(byId('whoosh'))} data-testid="whoosh-cuts">Whoosh on transitions</button>
          <button className="secondary-btn sm" onClick={() => void matchToGraphics(byId('pop'))} data-testid="pop-graphics">Pop on graphics</button>
        </div>
      </Section>
      <Section title="Mix">
        <Slider label="Music level while someone speaks (ducking)" value={project.audio.duckLevel * 100} min={5} max={100} format={(v) => `${Math.round(v)}%`}
          onChange={(v, l) => update((p) => ({ ...p, audio: { ...p.audio, duckLevel: v / 100 } }), { history: !l })} testId="duck-level" />
        <p className="muted small">Original clip sound (mute, volume, voice enhance, noise reduction) is under Edit → select a clip → Clip sound.</p>
      </Section>
    </div>
  );
}

function SoundRow({ def, onAdd }: { def: SoundDef; onAdd: () => void }) {
  return (
    <div className="list-item">
      <button className="mini-btn" onClick={() => void previewSound(def)} aria-label={`Preview ${def.name}`}>▶</button>
      <span className="grow">{def.icon} {def.name} <span className="muted small">{def.duration < 3 ? secs(def.duration) : 'loop'}</span></span>
      <button className="mini-btn" onClick={onAdd} aria-label={`Add ${def.name}`} data-testid={`add-sound-${def.id}`}>＋ Add</button>
    </div>
  );
}

function ItemInspector({ it }: { it: AudioItem }) {
  const assets = useEditor((s) => s.assets);
  const { patchAudioItem, removeAudioItem, setSelection } = useEditor.getState();
  const time = usePlayer((s) => s.time);
  const a = assets[it.assetId];
  const set = (patch: Partial<AudioItem>, live = false) => patchAudioItem(it.id, patch, { history: !live });
  const maxLen = it.loop ? 600 : Math.max(0.1, (a?.duration ?? it.length) - it.in);
  return (
    <div className="panel-stack" data-testid="audio-panel">
      <div className="panel-head">
        <div><h3 className="ellipsis">{a?.name ?? 'Audio'}</h3><p className="muted small">{it.kind === 'music' ? 'Music' : 'Sound effect'} · {secs(it.start)} → {secs(it.start + it.length)}</p></div>
        <button className="text-btn" onClick={() => setSelection(null)}>Done</button>
      </div>
      <Slider label="Volume" value={it.volume * 100} min={0} max={150} format={(v) => `${Math.round(v)}%`} onChange={(v, l) => set({ volume: v / 100 }, l)} testId="audio-volume" />
      <Slider label="Fade in" value={it.fadeIn} min={0} max={5} step={0.1} format={secs} onChange={(v, l) => set({ fadeIn: v }, l)} />
      <Slider label="Fade out" value={it.fadeOut} min={0} max={5} step={0.1} format={secs} onChange={(v, l) => set({ fadeOut: v }, l)} testId="audio-fadeout" />
      <Toggle label="Lower when someone speaks" hint="Automatic ducking under dialogue" checked={it.duck} onChange={(duck) => set({ duck })} testId="audio-duck" />
      <Toggle label="Loop to fill" checked={it.loop} onChange={(loop) => set({ loop, length: loop ? it.length : Math.min(it.length, (a?.duration ?? it.length) - it.in) })} />
      <Section title="Timing">
        <Slider label="Starts at" value={it.start} min={0} max={Math.max(it.start, 600)} step={0.05} format={secs} onChange={(v, l) => set({ start: v }, l)} />
        <Slider label="Length" value={it.length} min={0.1} max={Math.max(maxLen, it.length)} step={0.05} format={secs} onChange={(v, l) => set({ length: Math.min(v, maxLen) }, l)} />
        <Slider label="Start inside the song" value={it.in} min={0} max={Math.max(0, (a?.duration ?? 1) - 0.1)} step={0.1} format={secs} onChange={(v, l) => set({ in: v }, l)} />
        <div className="btn-row two">
          <button className="secondary-btn sm" onClick={() => set({ start: time })}>Start at playhead</button>
          <button className="secondary-btn sm" onClick={() => time > it.start && set({ length: Math.min(maxLen, time - it.start) })}>End at playhead</button>
        </div>
      </Section>
      <button className="danger-btn sm" onClick={() => removeAudioItem(it.id)} data-testid="delete-audio"><IconTrash /> Remove</button>
    </div>
  );
}
