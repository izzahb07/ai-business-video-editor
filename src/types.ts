export type AspectRatio = '9:16' | '16:9' | '1:1' | '4:5';
export type FitMode = 'fill' | 'fit';
export type AssetKind = 'video' | 'audio' | 'image';

/** An imported (or generated) media file. Immutable once imported. */
export interface Asset {
  id: string;
  kind: AssetKind;
  name: string;
  size: number;
  mime: string;
  /** Seconds (0 for images). Source time 0 = first video frame. */
  duration: number;
  /** Display width/height (after rotation metadata). 0 for audio. */
  width: number;
  height: number;
  codec: string | null;
  hasAudio: boolean;
  webCodecsDecodable: boolean;
  thumb: string;
  stored: boolean;
  /** Built-in, generated by the app (royalty-free by construction). */
  generated?: boolean;
  /** Speech transcript in SOURCE time (survives trims/splits). */
  transcript?: Transcript;
}

export interface WordTiming {
  text: string;
  start: number;
  end: number;
}

export interface Transcript {
  language: string;
  words: WordTiming[];
  source: 'on-device' | 'cloud';
  model: string;
  /** True when only phrase-level times were available; word times are interpolated. */
  approximateWords: boolean;
}

// ---------------- Clips ----------------

export interface ClipTransform {
  /** Crop rectangle as fractions of the source frame. */
  cropX: number;
  cropY: number;
  cropW: number;
  cropH: number;
  /** Degrees, clockwise. */
  rotation: number;
  /** 1 = fitted size. */
  scale: number;
  /** Offset as a fraction of output width/height. */
  x: number;
  y: number;
  flipH: boolean;
}

export interface Grade {
  exposure: number; // -100..100 (±2 stops)
  brightness: number;
  contrast: number;
  highlights: number;
  shadows: number;
  whites: number;
  blacks: number;
  saturation: number;
  vibrance: number;
  temperature: number;
  tint: number;
  fade: number; // 0..100
  vignette: number; // 0..100
  sharpness: number; // 0..100
  lutId: string | null;
  lutMix: number; // 0..100
}

export type TransitionType = 'none' | 'fade' | 'flash' | 'zoom' | 'whip' | 'blur';

export interface Clip {
  id: string;
  assetId: string;
  in: number;
  out: number;
  volume: number;
  muted: boolean;
  fit: FitMode;
  transform: ClipTransform;
  grade: Grade;
  /** Transition INTO this clip from the previous one. */
  transition: { type: TransitionType; duration: number };
  voice: { enhance: boolean; denoise: boolean };
}

// ---------------- Graphics overlays ----------------

export type AnimType =
  | 'none' | 'fade' | 'slide-up' | 'slide-down' | 'slide-left' | 'slide-right'
  | 'zoom' | 'pop' | 'bounce' | 'typewriter' | 'draw';
export type LoopType = 'none' | 'pulse' | 'float' | 'wiggle' | 'spin';

export interface Keyframe {
  /** Seconds from the overlay's start. */
  t: number;
  x: number;
  y: number;
  scale: number;
  rotation: number;
  opacity: number;
}

export interface TextStyle {
  font: string;
  weight: number;
  /** Pixels at 1080-wide reference. */
  size: number;
  color: string;
  highlightColor: string;
  align: 'left' | 'center' | 'right';
  uppercase: boolean;
  bg: { on: boolean; color: string; opacity: number; radius: number; padding: number };
  outline: { on: boolean; color: string; width: number };
  shadow: { on: boolean; color: string; blur: number };
}

export type ShapeType = 'arrow' | 'circle' | 'rect' | 'underline' | 'callout';
export type OverlayKind = 'text' | 'shape' | 'sticker' | 'image' | 'video';

export interface Overlay {
  id: string;
  kind: OverlayKind;
  name: string;
  start: number;
  duration: number;
  /** Centre position as fractions of the frame. */
  x: number;
  y: number;
  scale: number;
  rotation: number;
  opacity: number;
  keyframes: Keyframe[];
  animIn: { type: AnimType; duration: number };
  animOut: { type: AnimType; duration: number };
  loop: LoopType;
  // text
  text?: string;
  style?: TextStyle;
  // shape
  shape?: ShapeType;
  color?: string;
  strokeWidth?: number;
  /** Shape box as fractions of frame width/height. */
  w?: number;
  h?: number;
  label?: string;
  fill?: boolean;
  // sticker
  sticker?: string;
  // image / video (picture-in-picture)
  assetId?: string;
  in?: number;
  volume?: number;
  muted?: boolean;
  radius?: number;
  border?: { on: boolean; color: string; width: number };
  /** Full-frame colour panel behind the overlay (title cards / intros). */
  panel?: { on: boolean; color: string; opacity: number };
}

// ---------------- Captions ----------------

export interface CaptionSegment {
  id: string;
  text: string;
  /**
   * If anchored to a source asset, start/end/words are in that asset's SOURCE time and
   * follow the clip edits automatically. Otherwise they are timeline times.
   */
  anchorAssetId: string | null;
  start: number;
  end: number;
  words: WordTiming[];
  /** Indices of words to emphasise. */
  emphasis: number[];
}

export type CaptionAnim = 'none' | 'fade' | 'pop' | 'karaoke' | 'word' | 'bounce' | 'typewriter';

export interface CaptionStyle {
  template: string;
  font: string;
  weight: number;
  size: number;
  color: string;
  activeColor: string;
  emphasisColor: string;
  align: 'left' | 'center' | 'right';
  /** Vertical centre as fraction of height. */
  y: number;
  uppercase: boolean;
  animation: CaptionAnim;
  maxWords: number;
  bg: { on: boolean; color: string; opacity: number; radius: number; padding: number };
  outline: { on: boolean; color: string; width: number };
  shadow: { on: boolean; color: string; blur: number };
}

export interface Captions {
  enabled: boolean;
  segments: CaptionSegment[];
  style: CaptionStyle;
  language: 'auto' | 'en' | 'ms';
}

// ---------------- Audio ----------------

export interface AudioItem {
  id: string;
  assetId: string;
  kind: 'music' | 'sfx';
  start: number;
  in: number;
  /** Seconds on the timeline (may exceed the file when looping). */
  length: number;
  loop: boolean;
  volume: number;
  fadeIn: number;
  fadeOut: number;
  /** Lower this track while someone speaks. */
  duck: boolean;
}

export interface AudioSettings {
  items: AudioItem[];
  /** Music gain while speech is detected (0..1). */
  duckLevel: number;
}

// ---------------- Project ----------------

export interface LutRef {
  id: string;
  name: string;
  size: number;
}

export interface ProjectSettings {
  aspect: AspectRatio;
  background: 'blur' | 'black';
}

export interface Project {
  id: string;
  name: string;
  clips: Clip[];
  overlays: Overlay[];
  captions: Captions;
  audio: AudioSettings;
  luts: LutRef[];
  settings: ProjectSettings;
}

export type ExportResolution = 720 | 1080 | 2160;
export type ExportQuality = 'high' | 'medium' | 'low';

export interface ExportSettings {
  resolution: ExportResolution;
  fps: 24 | 25 | 30 | 60;
  quality: ExportQuality;
  audioBitrate: 128000 | 192000 | 256000;
}
